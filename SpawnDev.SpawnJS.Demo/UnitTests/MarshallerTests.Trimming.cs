using System;
using System.Collections.Generic;
using System.Diagnostics.CodeAnalysis;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using SpawnDev.SpawnJS.JSObjects;

namespace SpawnDev.SpawnJS.Demo.UnitTests
{
    // Trimming (SpawnJS.TestRunner --trimmed runs the suite against a trimmed Release publish; an untrimmed run passes
    // these either way). A wrapper reached only through reflection - an array / list element, a POCO member - is built
    // by Activator.CreateInstance and nothing calls its constructor statically: the embedded ILLink.Descriptors.xml
    // (generated by Tools/GenerateTrimDescriptor.cs) keeps the constructors of every kept wrapper. The wrapper types
    // below are used nowhere else in the library or this demo, so nothing else keeps their constructors.
    public static partial class MarshallerTests
    {
        // a wrapper this app defines, as a POCO member: the generated codec names its constructor
        public class TrimProbeMember : SpawnJSObject { public TrimProbeMember(SpawnJSObjectReference r) : base(r) { } public string Name => JSRef!.Get<string>("name"); }
        public class TrimProbeHolder { public TrimProbeMember? Item { get; set; } }

        static Dictionary<string, string>[] TrimProbeSource() => new[]
        {
            new Dictionary<string, string> { ["name"] = "a" },
            new Dictionary<string, string> { ["name"] = "b" },
        };

        static void TrimmingTests()
        {
            Test("Trimming.BuiltInWrapperAsArrayElement", () =>
            {
                JS.Set(K, TrimProbeSource());
                var got = JS.Get<GamepadButton[]>(K)!;
                AssertEqual(got.Length, 2, "length");
                AssertEqual(got[1].JSRef!.Get<string>("name"), "b", "element wrapper");
                foreach (var w in got) w.Dispose();
            });

            Test("Trimming.BuiltInWrapperAsListElement", () =>
            {
                JS.Set(K, TrimProbeSource());
                var got = JS.Get<List<BluetoothRemoteGATTDescriptor>>(K)!;
                AssertEqual(got.Count, 2, "count");
                AssertEqual(got[0].JSRef!.Get<string>("name"), "a", "element wrapper");
                foreach (var w in got) w.Dispose();
            });

            Test("Trimming.ConsumerWrapperAsPocoMember", () =>
            {
                JS.Set(K, new Dictionary<string, Dictionary<string, string>> { ["item"] = new() { ["name"] = "m" } });
                var got = JS.Get<TrimProbeHolder>(K)!;
                AssertEqual(got.Item?.Name, "m", "member wrapper");
                got.Item?.Dispose();
            });

            Test("Trimming.DescriptorListsEveryWrapper", DescriptorListsEveryWrapper);
        }

        // Every wrapper the marshaller can build must be in the descriptor, or a trimmed app that reads it as an array
        // element fails with MissingMethodException. Rerun Tools/GenerateTrimDescriptor.cs to fix this test.
        [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = "Lists the types an untrimmed run has; a trimmed run has no descriptor to compare and skips.")]
        static void DescriptorListsEveryWrapper()
        {
            var assembly = typeof(SpawnJSObject).Assembly;
            using var stream = assembly.GetManifestResourceStream("ILLink.Descriptors.xml");
            if (stream == null) Skip("the trimmer removed the descriptor (a trimmed run)");
            var listed = Regex.Matches(new StreamReader(stream!).ReadToEnd(), "<type fullname=\"([^\"]+)\"")
                .Select(m => m.Groups[1].Value).ToHashSet();
            var missing = assembly.GetTypes()
                .Where(IsWrapper)
                .Select(t => t.FullName!.Replace('+', '/'))
                .Where(n => !listed.Contains(n))
                .OrderBy(n => n, StringComparer.Ordinal)
                .ToList();
            Assert(missing.Count == 0, $"{missing.Count} wrapper(s) not in ILLink.Descriptors.xml (run Tools/GenerateTrimDescriptor.cs): {string.Join(", ", missing.Take(20))}");
        }

        // the generator's rule: a non-abstract SpawnJSObject subclass (open generics included) with a public constructor
        [UnconditionalSuppressMessage("Trimming", "IL2070", Justification = "Untrimmed comparison only, see DescriptorListsEveryWrapper.")]
        static bool IsWrapper(Type t)
        {
            if (!t.IsClass || t.IsAbstract || t.FullName == null || t.FullName.Contains('<')) return false;
            if (t.GetConstructors().Length == 0) return false;
            if (t == typeof(SpawnJSObject)) return true;
            for (var b = t.BaseType; b != null; b = b.BaseType)
                if ((b.IsGenericType ? b.GetGenericTypeDefinition() : b) == typeof(SpawnJSObject)) return true;
            return false;
        }
    }
}
