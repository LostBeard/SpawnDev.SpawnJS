#:package System.Reflection.MetadataLoadContext@10.0.0
#:property LangVersion=latest

// Writes SpawnDev.SpawnJS/ILLink.Descriptors.xml: one entry per wrapper type (every non-abstract SpawnJSObject
// subclass with a public constructor) keeping its public constructors, required="false" so the entry applies only to
// a wrapper the app keeps anyway.
//
//   dotnet build SpawnDev.SpawnJS -c Release
//   dotnet run Tools/GenerateTrimDescriptor.cs
//
// Rerun after adding a wrapper. The suite test Trimming.DescriptorListsEveryWrapper fails, naming the missing types,
// when a wrapper is not in the descriptor.
//
// Why a list and not a wildcard: a namespace wildcard cannot select "constructors of wrapper types". With
// <method name=".ctor" /> it hits the enums, static classes and compiler-generated state machines in the namespace
// too (IL2009 warnings in every trimmed app), and preserve="all" / "methods" keep the whole API of every kept wrapper
// (about 650 KB of the demo's 2.6 MB SpawnDev.SpawnJS.wasm).

using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;

var repo = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(GetSourcePath())!, ".."));
var dll = Path.Combine(repo, "SpawnDev.SpawnJS", "bin", "Release", "net10.0", "SpawnDev.SpawnJS.dll");
if (!File.Exists(dll)) { Console.Error.WriteLine($"build first: {dll} not found"); return 1; }

var paths = new List<string>(Directory.GetFiles(RuntimeEnvironment.GetRuntimeDirectory(), "*.dll")) { dll };
var backgroundServices = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".nuget", "packages", "spawndev.backgroundservices");
if (Directory.Exists(backgroundServices))
    paths.AddRange(Directory.GetFiles(backgroundServices, "SpawnDev.BackgroundServices.dll", SearchOption.AllDirectories).Where(p => p.Contains("net10.0")).Take(1));

using var mlc = new MetadataLoadContext(new PathAssemblyResolver(paths));
var assembly = mlc.LoadFromAssemblyPath(dll);
var baseType = assembly.GetType("SpawnDev.SpawnJS.SpawnJSObject", throwOnError: true)!;

var wrappers = assembly.GetTypes()
    .Where(t => t.IsClass && !t.IsAbstract && !t.Name.Contains('<') && !t.FullName!.Contains('<'))
    .Where(t => t == baseType || IsSubclassOf(t, baseType))
    .Where(t => t.GetConstructors(BindingFlags.Public | BindingFlags.Instance).Length > 0)
    .Select(t => t.FullName!.Replace('+', '/'))
    .OrderBy(n => n, StringComparer.Ordinal)
    .ToList();

var xml = new StringBuilder();
xml.Append("""
<!--
  GENERATED by Tools/GenerateTrimDescriptor.cs - rerun it after adding a wrapper (the suite test
  Trimming.DescriptorListsEveryWrapper fails, naming the missing types, until you do).

  The one thing the trimmer cannot see in this library: a wrapper is built by the marshaller graph through
  Activator.CreateInstance(type, jsRef) (SpawnJSObjectMarshaller.JSToNet), and when the wrapper type is only an
  array / list element, a Task result or a POCO member, the type comes from reflection (GetElementType,
  GetGenericArguments, PropertyType), where [DynamicallyAccessedMembers] cannot follow it. Nothing calls that
  constructor statically, so without this file a trimmed app fails the first time it reads such a wrapper:
  "MissingMethodException: MissingConstructor_Name, <wrapper>".

  Each entry keeps the public constructors of one wrapper (every non-abstract SpawnJSObject subclass). Nothing else:
  the rest of a wrapper's API is trimmed like any other code. POCO members need nothing here, the generated codecs
  (SpawnDev.SpawnJS.Generators) name every accessor they use.

  required="false" is the important part: it does NOT root these types. A wrapper the app never mentions is still
  removed entirely. It only says that IF a wrapper is kept, its constructors are kept with it.

  Embedded as a resource so it travels in the package: an app can turn on PublishTrimmed without knowing this exists.
  SpawnJS.TestRunner has a trimmed mode that runs the suite against a trimmed Release publish.
-->
<linker>
  <assembly fullname="SpawnDev.SpawnJS">

""");
foreach (var name in wrappers)
    xml.Append($"    <type fullname=\"{System.Security.SecurityElement.Escape(name)}\" required=\"false\"><method name=\".ctor\" /></type>\n");
xml.Append("""

  </assembly>
</linker>

""");

// ILLink rejects the whole file (IL1003, every trimmed publish of every app fails) if a comment holds a double hyphen
var text = xml.ToString();
var comment = text.Substring(4, text.IndexOf("-->", StringComparison.Ordinal) - 4);
if (comment.Contains("--")) { Console.Error.WriteLine("the header comment contains a double hyphen, which XML forbids"); return 1; }
_ = System.Xml.Linq.XDocument.Parse(text);

var target = Path.Combine(repo, "SpawnDev.SpawnJS", "ILLink.Descriptors.xml");
File.WriteAllText(target, xml.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));
Console.WriteLine($"{wrappers.Count} wrapper types -> {target}");
return 0;

static bool IsSubclassOf(Type t, Type baseType)
{
    for (var b = t.BaseType; b != null; b = b.BaseType)
    {
        var d = b.IsGenericType ? b.GetGenericTypeDefinition() : b;
        if (d == baseType) return true;
    }
    return false;
}

static string GetSourcePath([System.Runtime.CompilerServices.CallerFilePath] string path = "") => path;
